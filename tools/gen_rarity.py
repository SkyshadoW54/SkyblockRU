# Подземельная броня — тот же тип предмета, но со словом DUNGEON посередине.
# Перебирали только «редкость + тип», и вся подземельная экипировка оставалась
# английской: в словаре лежало «LEGENDARY BOOTS», а игра писала «LEGENDARY
# DUNGEON BOOTS». Строка редкости есть у КАЖДОГО предмета, поэтому пропущенная
# комбинация видна сразу и на самом заметном месте.
PREFIXES = {
    "": "",
    "DUNGEON": "ПОДЗЕМЕЛЬЯ",
}


def main() -> int:
    exact: dict[str, str] = {}

    for rarity_en, forms in RARITY.items():
        # редкость сама по себе, без типа предмета
        exact[rarity_en] = forms[0]
        for type_en, (type_ru, gender) in TYPES.items():
            for prefix_en, prefix_ru in PREFIXES.items():
                # По-русски приставка идёт ПОСЛЕ существительного:
                # «МИФИЧЕСКИЕ БОТИНКИ ПОДЗЕМЕЛЬЯ», а не «ПОДЗЕМЕЛЬЯ БОТИНКИ».
                key = f"{rarity_en} {prefix_en} {type_en}" if prefix_en                     else f"{rarity_en} {type_en}"
                value = f"{forms[GENDER[gender]]} {type_ru}"
                if prefix_ru:
                    value += f" {prefix_ru}"
                exact[key] = value

    pack = {
        "id": "rarity",
        "priority": 45,
        "_comment": "СГЕНЕРИРОВАНО tools/gen_rarity.py — руками не править, правь генератор. "
                    "Строка редкости есть у КАЖДОГО предмета SkyBlock, поэтому комбинации "
                    "перебираются целиком: забудешь одну — она полезет в игре.",
        "exact": exact,
    }

    OUT.write_text(json.dumps(pack, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"редкостей: {len(RARITY)}, типов предметов: {len(TYPES)}")
    print(f"записей: {len(exact)}")
    print(f"записано: {OUT.relative_to(ROOT)}")
    return 0


