"""
Правила истории БАЗАРА и БАНКА — комбинаторика, которую не перечислить.

Что закрывается. Подсказка «Bazaar History» и выписка банка устроены одинаково:
время, действие, количество, имя предмета, ник. Имён предметов тысячи, единиц
времени четыре, действий шесть — поштучно это 780 строк в очереди и бесконечный
хвост впереди. Одно правило на действие закрывает и то, чего мы не видели.

⚠️ Строка РАЗРЕЗАНА переносом, и половин две:

    {n}d ago Instant Buy of {n}x Raw Cod        <- первая
    for {n} coins by _Skyshadow_                <- вторая

Обе нужны: без второй на экране остаётся английский хвост под русской строкой.
Разрезку выбирает ширина окна ИГРОКА, поэтому склейкой в абзац такое не лечится —
у другого игрока границы пройдут в другом месте.

⚠️ ЕДИНИЦА ВРЕМЕНИ СТОИТ В САМОМ ШАБЛОНЕ, а не в захвате. Захват подставился бы
как есть («3d назад»), а перевести его правилом нельзя: правило на строку одно.
Отсюда перечисление 4 единиц × 6 действий. То же решение, что у сезонов
и редкостей: перечисление ОСОЗНАННОЕ, потому что список конечен и приходит
от сервера.

⚠️ ЦВЕТА НЕТ И НЕ ВЫДУМЫВАЕМ. §-коды этой подсказки не собраны
(в `dump/paragraph-colors.json` её нет), а зашитый на глаз цвет — записанная
грабля проекта. Без кодов работает `restyleFromSource`: числа, имя предмета
и ник уцелевают в переводе ДОСЛОВНО и получают цвет самого оригинала.

⚠️ «Bank Interest» переводится ГЛОССАРИЕМ через `tg`, а не отдельным правилом.
Сервер пишет и «by Bank Interest», и «by Bank Interest (x3)» — второй формы
в словаре нет, а глоссарий подставляет термин ВНУТРИ строки и берёт обе.
Проверено по дампу: «Bank Interest» встречается только здесь (5 строк),
так что в прозу глоссарий не залезет.

Запуск:
  python tools/gen_bazaar.py            собрать словарь
  python tools/gen_bazaar.py --dry      показать, ничего не записывая
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG = "ru_ru"
OUT = ROOT / "src" / "main" / "resources" / "assets" / "skyblockru" / "packs" / LANG / "48-bazaar.json"

# Число с разделителями плюс необязательный суффикс тысяч и миллионов.
# ⚠️ Писать `[\d,.]+` без суффикса нельзя: сервер пишет «for 1.2M coins»,
# и правило прошло бы мимо самой заметной сделки.
MONEY = r"([\d,.]+[kM]?)"
COUNT = r"([\d,]+)"

# Единицы времени базара: сервер пишет их одной буквой вплотную к числу.
UNITS = [("s", "с"), ("m", "мин"), ("h", "ч"), ("d", "д")]

# Действия базара. Список от сервера, замер по живому дампу:
# Instant Sell 453, Instant Buy 249, Claimed Sell Offer 15,
# Cancelled Sell Offer 7, Claimed Buy Offer 6, Cancelled Buy Order 3.
# ⚠️ Термины взяты из 20-ui.json («Мгновенная продажа», «Предложение о продаже»,
# «Заказ на покупку»), а не придуманы заново: эти же слова игрок видит
# на кнопках рядом, и разнобой между кнопкой и историей заметен сразу.
ACTIONS = [
    ("Instant Sell", "мгновенная продажа"),
    ("Instant Buy", "мгновенная покупка"),
    ("Claimed Sell Offer", "забрано предложение о продаже"),
    ("Cancelled Sell Offer", "отменено предложение о продаже"),
    ("Claimed Buy Offer", "забран заказ на покупку"),
    ("Cancelled Buy Order", "отменён заказ на покупку"),
]

# Единицы времени банка: там они словом, и форм у каждой две.
BANK_UNITS = [
    ("sec", "с"), ("secs", "с"),
    ("min", "мин"), ("mins", "мин"),
    ("hour", "ч"), ("hours", "ч"),
    ("day", "д"), ("days", "д"),
]


def rules() -> list[dict]:
    out: list[dict] = []

    out.append({
        "_": "ИСТОРИЯ БАЗАРА, первая половина строки. Единица времени и действие"
             " стоят в шаблоне, потому что правило на строку одно и захват"
             " перевести нечем. Имя предмета не трогаем — по нему ищут на базаре.",
    })
    for unit, unit_ru in UNITS:
        for action, action_ru in ACTIONS:
            out.append({
                "p": rf"^{COUNT}{unit} ago {action} of {COUNT}x (.+)$",
                "r": f"$1 {unit_ru} назад {action_ru} $2x $3",
            })

    out.append({
        "_": "ВТОРАЯ ПОЛОВИНА той же строки — её отрезал перенос. Ник в захвате:"
             " он бывает и голым, и с рангом («[MVP+] Player»), поэтому шаблон"
             " не сужаем. Без этого правила под русской строкой оставался бы"
             " английский хвост.",
        "p": rf"^for {MONEY} coins by (.+)$",
        "r": "за $1 монет — $2",
    })

    out.append({
        "_": "Multi-sell — продажа нескольких товаров разом. Перевода термина"
             " в словарях не нашлось, взят по смыслу: «массовая продажа».",
    })
    for unit, unit_ru in UNITS:
        out.append({
            "p": rf"^{COUNT}{unit} ago Multi-sell for {MONEY} coins$",
            "r": f"$1 {unit_ru} назад массовая продажа за $2 монет",
        })

    out.append({
        "_": "Строка списка с давностью: «- 5x SomePlayer 3m ago». В нашем дампе"
             " её нет — пришла от игроков, — но форма та же, что у истории выше,"
             " и единица времени так же требует перевода.",
    })
    for unit, unit_ru in UNITS:
        out.append({
            "p": rf"^- {COUNT}x (.+) {COUNT}{unit} ago$",
            "r": f"- $1x $2 $3 {unit_ru} назад",
        })

    out.append({
        "_": "СПИСОК ПРЕДЛОЖЕНИЙ базара: «64x Bone for 1,234 coins». Имя предмета"
             " не трогаем. Форма совпадает с уже купленным «{n}x Dandelion"
             " за {n} монет» — проверено tools/try_rule.py.",
        "p": rf"^{COUNT}x (.+) for {COUNT} coins$",
        "r": "$1x $2 за $3 монет",
    })

    out.append({
        "_": "ВЫПИСКА БАНКА. «tg» переводит захват по словарю: там либо ник"
             " (словарь его не знает и вернёт как есть), либо «Bank Interest»,"
             " который берёт глоссарий ниже — вместе с формой «(x3)».",
    })
    for unit, unit_ru in BANK_UNITS:
        out.append({
            "p": rf"^([+-]) {MONEY}, {COUNT} {unit} ago by (.+)$",
            "r": f"$1 $2, $3 {unit_ru} назад — $4",
            "tg": True,
        })

    out.append({
        "_": "ТА ЖЕ ВЫПИСКА, но БЕЗ «by …»: перевод внёс сам игрок, и сервер"
             " никого не называет. Форму нашли по строкам от игроков — у нас"
             " в дампе её не было вовсе, а охват у неё 20+ установок, то есть"
             " видит её почти каждый. Правило с «by» её не ловило: там хвост"
             " обязателен.",
    })
    for unit, unit_ru in BANK_UNITS:
        out.append({
            "p": rf"^([+-]) {MONEY}, {COUNT} {unit} ago$",
            "r": f"$1 $2, $3 {unit_ru} назад",
        })
    out.append({
        "_": "«Just now» — та же выписка, когда операция прошла только что.",
        "p": rf"^([+-]) {MONEY}, Just now$",
        "r": "$1 $2, только что",
    })

    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry", action="store_true", help="только показать")
    args = parser.parse_args()

    body = {
        "id": "bazaar",
        "priority": 25,
        "_comment": (
            "История базара и выписка банка — генерируется tools/gen_bazaar.py,"
            " руками не править. Строка истории РАЗРЕЗАНА переносом на две,"
            " и правил тоже два: без второго под русской строкой остаётся"
            " английский хвост. Единица времени и действие стоят в шаблоне"
            " ОСОЗНАННО: правило на строку одно, и захват перевести нечем."
        ),
        "only": ["item_lore"],
        "glossary": {
            "Bank Interest": "проценты банка",
        },
        "regex": rules(),
    }

    count = sum(1 for rule in body["regex"] if rule.get("p"))
    print(f"правил: {count}, глоссарий: {len(body['glossary'])}")
    for rule in body["regex"][:3]:
        if rule.get("p"):
            print(f"   {rule['p']}")
            print(f"     -> {rule['r']}")
    if args.dry:
        print("сухой прогон: файл не записан")
        return 0

    OUT.write_text(json.dumps(body, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    print(f"записано: {OUT.relative_to(ROOT)}")
    print("⚠️ впиши файл в packs/index.json, иначе он молча не загрузится")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
