def name_pattern(name: str) -> str:
    """Шаблон имени, который видит его СКВОЗЬ §-коды.

    ⚠️ Hypixel красит слова имени ПОРОЗНЬ: «в §2Backwater§7 §2Bayou§7».
    Поиск подстроки такое имя не находит НИ РАЗУ — записанная грабля проекта
    (так же терялись «Магический поиск» и длинные имена мэров).
    """
    words = [re.escape(w) for w in name.split(" ")]
    return r"(?:§.|\s)+".join(words)


def substitute(text: str, name: str, forms: dict[str, str]) -> str:
    """Подставить имя в нужной форме там, где это безопасно."""
    # ⚠️ РОДИТЕЛЬНЫЙ идёт БЕЗ предлога — его задаёт существительное слева
    if "род" in forms:
        res, prev = [], 0
        for m in re.finditer(name_pattern(name) + r"(?![A-Za-z])", text):
            if STOP.match(CODES.sub("", text[m.end():])):
                continue
            if not GEN_AFTER.search(text[:m.start()]):
                continue
            res.append(text[prev:m.start()] + forms["род"])
            prev = m.end()
        res.append(text[prev:])
        text = "".join(res)
    for prep, form in forms.items():
        if prep in ("им", "род"):
            continue
        pat = re.compile(rf"(\b{prep}\s+(?:§.)*){name_pattern(name)}(?![A-Za-z])")
        out, prev, res = [], 0, []
        for m in pat.finditer(text):
            # ⚠️ §-КОД МЕШАЕТ ЗАЩИТЕ: у «на §dThe End§7 Island» справа от имени
            # идёт «§7 Island», и признак «дальше английское слово» не совпадал —
            # составное имя разрывалось («на Краю Island»). Коды снимаем.
            if STOP.match(CODES.sub("", text[m.end():])):
                continue
            if LEFT_STOP.search(text[:m.start() + len(m.group(1))]):
                continue
            out.append((m.start(), m.end(), m.group(1)))
        for start, end, head in out:
            # «куда?» — винительный, если слева глагол движения
            use = form
            # ⚠️ У НЕОДУШЕВЛЁННЫХ винительный совпадает с ИМЕНИТЕЛЬНЫМ
            # (мужской род и множественное), и перечислять 26 одинаковых форм
            # незачем. Отдельно заданы только женские на -а/-я: «Гробница» ->
            # «Гробницу». NPC это не задевает: предлога «в/на» у них не бывает.
            if prep in ("в", "на") and (forms.get("вин") or forms.get("им"))                     and MOVE.search(text[:start]):
                # ⚠️ глагол ищем ДО предлога: MOVE кончается на $, и кусок
                # с самим «в » ему не подходит — признак молчал на всех трёх
                use = forms.get("вин") or forms["им"]
            res.append(text[prev:start] + head + use)
            prev = end
        res.append(text[prev:])
        text = "".join(res)

    # ⚠️ ИМЕНИТЕЛЬНЫЙ — голое имя, без предлога и без управляющего слова:
    # «Источник: IV: Сезон Джерри», «- Сезон Джерри (IV)», «{n}-й Сезон Джерри».
    # Идёт ПОСЛЕДНИМ, чтобы падежные формы успели забрать свои места.
    #
    # ⚠️ Признак ПОЗИЦИИ берём у `fix_full_headings`, а не пишем свой: копия
    # признака в этом проекте расходилась трижды и всегда молча. Он же несёт
    # две защиты, каждая — записанная грабля: род («этот Sinker» -> «этот
    # Грузило») и составное имя («Season of Jerry Experiments»).
    if "им" in forms and re.search(name_pattern(name), text):
        import fix_full_headings as headings   # ленивый: тянет status
        res, prev = [], 0
        for m in re.finditer(name_pattern(name) + r"(?![A-Za-z])", text):
            if m.start() < prev:
                continue
            # ⚠️ ПРИТЯЖАТЕЛЬНОЕ «'s» — записанная грабля проекта: «Hoppity's
            # Hunt» -> «Хоппити's Hunt», «Jacob's Farming Contest» ->
            # «Джейкоб's Farming Contest». `standalone` его НЕ ловит: он ищет
            # справа заглавную букву, а апостроф ею не является. Спрашиваем
            # тот же STOP, что и остальные ветки.
            if STOP.match(CODES.sub("", text[m.end():])):
                continue
            if not headings.nominative_at(text, m.start()):
                continue
            if not headings.gender_safe(text, m.start()):
                continue
            if not headings.standalone(text, m.start(), m.end()):
                continue
            res.append(text[prev:m.start()] + forms["им"])
            prev = m.end()
        res.append(text[prev:])
        text = "".join(res)
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--show", type=int, default=10)
    args = ap.parse_args()

    rows = json.loads(CORPUS.read_text(encoding="utf-8")).get("paragraphs") or []
    work = json.loads(WORK.read_text(encoding="utf-8"))
    ready = work["rows"]

    made, shown = {}, 0
    for row in rows:
        ru = row.get("ru") or ""
        key = row.get("text") or row.get("key") or ""
        if not ru or not key:
            continue
        new = ru
        for name, forms in PLACES.items():
            if re.search(name_pattern(name), new):
                new = substitute(new, name, forms)
        if new == ru:
            continue
        # ⚠️ уже переведённое РУКАМИ не трогаем: наша подстановка беднее
        if key in ready and ready[key].get("ru") not in (None, "", ru):
            continue
        made[key] = {"base": ru, "ru": new, "done": True,
                     "_": "локация/NPC в прозе: падеж по предлогу слева"}
        if shown < args.show:
            print(f"  {CODES.sub('', ru)[:74]}")
            print(f"  -> {CODES.sub('', new)[:74]}\n")
            shown += 1

    print(f"абзацев с подстановкой: {len(made)}")
    if not args.write:
        print("\nСУХОЙ ПРОГОН. Записать: --write")
        return 0
    ready.update(made)
    work["rows"] = ready
    WORK.write_text(json.dumps(work, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    print(f"записано в заготовку: {len(ready)} абзацев")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
