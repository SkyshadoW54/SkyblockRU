# -*- coding: utf-8 -*-
"""
Отсев ОБРЕЗКОВ боковой панели — оба края, без сети и без игры.

⚠️ Зачем. `collect_server.panel_cuts` УБИРАЕТ строки из работы: признанная
обрезком строка не попадёт ни в очередь, ни в покупку. Значит ошибка стоит
не лишней записи, а ПОТЕРЯННОЙ надписи Hypixel — и потеряется она молча,
потому что выглядит как «эту строку нам просто не присылали».

⚠️ Признак «оборвано посреди слова» В ОДИНОЧКУ НЕВЕРЕН, и это замерено
13.08 на нашей чистой игре: он задевал 39 законных строк — римские уровни
(«Farmhand VII» против «Farmhand VIII»), множественное число («Upgrade Item»
/ «Items»), пары предметов («Black Wool» / «Black Woolen Yarn»). Держат его
три подпорки, и каждая проверяется здесь своим случаем:
  * длинная строка САМА прошла порог (мусор склейки приходит от одной
    установки: «VillageAA» прислала 1 против 76 у « Village»);
  * продолжение не «s»;
  * строка не кончается римским уровнем.

Запуск:
  python tools/check_panel_cuts.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from collect_server import panel_cuts  # noqa: E402

FLOOR = 3
ICON = ""

# (строки панели с числом приславших, что обязано отсеяться, зачем случай)
CASES = [
    (
        "настоящий обрезок: целая строка прошла порог",
        [(f"{ICON} Bazaar Al", 38), (f"{ICON} Bazaar Alley", 52)],
        {f"{ICON} Bazaar Al"},
    ),
    (
        # ⚠️ Обрезок бывает ЧАЩЕ целой строки, и одной частоты тут мало.
        # Решает подтверждение НАШИМ дампом: там игра чистая, без соседей.
        "обрезок чаще целой, но целая есть в нашем дампе — обрезок",
        [(f"{ICON} The Garde", 24), (f"{ICON} The Garden", 22)],
        {f"{ICON} The Garde"},
        {f"{ICON} The Garden"},
    ),
    (
        # ⚠️ ЦЕНА той же правки, названная прямо: без подтверждения дампом
        # такую пару мы пропускаем. Это осознанный размен — 33 пропущенных
        # обрезка против 4 ИСПОРЧЕННЫХ законных строк (замер 13.08).
        "обрезок чаще целой и целой нет в дампе — пропускаем (цена правки)",
        [(f"{ICON} The Garde", 24), (f"{ICON} The Garden", 22)],
        set(),
    ),
    # --- ЗАВЕДОМО ИСТИННЫЕ: обязаны уцелеть ---
    (
        "мусор склейки не делает целую строку обрезком",
        [(f"{ICON} Village", 76), (f"{ICON} VillageAA", 1),
         (f"{ICON} Villageutpost", 2)],
        set(),
    ),
    (
        # ⚠️ 13.08: с ростом числа игроков мусор склейки начал ПРОХОДИТЬ порог,
        # и целая « Village» (121 установка) была названа обрезком от
        # « Villageutpost» (3 установки). Одного порога стало мало.
        "мусор склейки прошёл порог, но приходит РЕЖЕ — всё равно не обрезок",
        [(f"{ICON} Village", 121), (f"{ICON} Villageutpost", 3),
         (f"{ICON} ForestCamp", 4), (f"{ICON} Forest", 76)],
        set(),
    ),
    (
        "длинная строка ЧАЩЕ короткой — это настоящий обрезок",
        [(f"{ICON} Combat Se", 47), (f"{ICON} Combat Settlement", 77)],
        {f"{ICON} Combat Se"},
    ),
    (
        "римские уровни — разные строки, а не обрыв",
        [("Farmhand VII", 20), ("Farmhand VIII", 30)],
        set(),
    ),
    (
        "множественное число — законная пара",
        [("Upgrade Item", 20), ("Upgrade Items", 30)],
        set(),
    ),
    (
        "суффикс тысяч у числа — не обрыв (строка кончается не буквой)",
        [("Bank: {n}", 30), ("Bank: {n}k", 40)],
        set(),
    ),
    (
        "короткая строка под признак не идёт",
        [("Sam", 30), ("Samuel", 40)],
        set(),
    ),
    (
        "продолжение с ПРОБЕЛА — слово кончилось, обрыва нет",
        [(f"{ICON} Forest", 42), (f"{ICON} Forest Camp", 40)],
        set(),
    ),
]


def main() -> int:
    bad = 0
    for case in CASES:
        # четвёртый элемент необязателен: строки, которым верим как ЦЕЛЫМ
        # без порога (наш локальный дамп)
        name, rows, expect = case[0], case[1], case[2]
        trusted = case[3] if len(case) > 3 else frozenset()
        got = set(panel_cuts(rows, FLOOR, trusted))
        if got == expect:
            print(f"  ок      {name}")
            continue
        bad += 1
        print(f"  СЛОМАНО {name}")
        print(f"          лишнее:  {sorted(got - expect)}")
        print(f"          потеряно: {sorted(expect - got)}")

    print()
    if bad:
        print(f"СЛОМАНО: {bad} — отсев обрезков трогает не то")
        return 1
    print("СЛОМАНО: 0 — обрезки уходят, законные строки остаются")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
