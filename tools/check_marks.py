# -*- coding: utf-8 -*-
"""
МАРКЕРЫ РАЗМЕТКИ — чиним искажённые, не трогаем чужое.

Зачем. Перевод уходит модели с масками: {c1}…{/c1} для цвета, {i1} для
значка, {n}/{s} для чисел и ников. Раньше `accept()` бракова́л абзац целиком,
если маркер вернулся хоть чуть-чуть не таким, — то есть оплаченный перевод
выбрасывался из-за одного знака.

Приём взят у чужого мода (fridorin/Skyblock-Translator-Mod): он восстанавливает
свои метки регуляркой, принимающей {F0}, (F0), [F0], _F0_ и даже {ф0}
с кириллической буквой. Машинный переводчик метку корёжит, и жёсткая сверка
теряла бы каждый такой ответ.

⚠️ Для НАШЕГО языка риск особый: маркер {c1} пишется ЛАТИНСКОЙ «c», а перевод
русский — кириллическая «с» неотличима на глаз ни в редакторе, ни в дифе.

⚠️ Опасность правки — обратная: слишком жадная регулярка съест ЧУЖОЕ.
Рядом живут дырки {n} и {s}, размеры «стена {n}x{n}», сноски «(c)».
Поэтому проверяем оба края: чинится искажённое И не трогается остальное.

    python tools/check_marks.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from translate_tooltips import normalize_marks  # noqa: E402

# (что пришло, что должно стать, пояснение)
CASES = [
    ("{c1}текст{/c1}", "{c1}текст{/c1}", "целый маркер не трогаем"),
    ("{с1}текст{/с1}", "{c1}текст{/c1}", "КИРИЛЛИЧЕСКАЯ с -> латинская"),
    ("(c1)текст(/c1)", "{c1}текст{/c1}", "круглые скобки"),
    ("[c1]текст[/c1]", "{c1}текст{/c1}", "квадратные скобки"),
    ("{ c1 }текст{ /c1 }", "{c1}текст{/c1}", "пробелы внутри"),
    ("{_c1_}текст{_/c1_}", "{c1}текст{/c1}", "подчёркивания с обеих сторон"),
    ("{C1}текст{/C1}", "{c1}текст{/c1}", "заглавная C"),
    ("{i1} значок", "{i1} значок", "целый маркер значка"),
    ("(i2) значок", "{i2} значок", "значок в круглых скобках"),
    ("{і3} значок", "{i3} значок", "КИРИЛЛИЧЕСКАЯ і в значке"),
    # ⚠️ Второй край: чужое трогать нельзя.
    ("Даёт {n} монет", "Даёт {n} монет", "дырка {n} — не маркер"),
    ("Урон {s} игроку", "Урон {s} игроку", "дырка {s} — не маркер"),
    ("стена {n}x{n}", "стена {n}x{n}", "размеры не маркеры"),
    ("Стоимость: 10 (c)", "Стоимость: 10 (c)", "буква без цифры не маркер"),
    ("шанс 5% (2)", "шанс 5% (2)", "цифра без буквы не маркер"),
]


def main():
    bad = 0
    for given, want, why in CASES:
        got = normalize_marks(given)
        ok = got == want
        note = "" if ok else f"  {given!r} -> {got!r}, ждали {want!r}"
        print("%s %-36s%s" % ("  [ok]  " if ok else "  [ПЛОХО]", why, note))
        if not ok:
            bad += 1

    print()
    if bad:
        print(f"СЛОМАНО: {bad}")
        return 1
    print(f"маркеры: чинится искажённое ({len(CASES)} случаев), чужое цело")
    return 0


if __name__ == "__main__":
    sys.exit(main())
