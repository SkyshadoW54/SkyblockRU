package ru.skyblockru.core;

import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Решение «склеивать ли кусок подсказки в абзац» — по одним только ЦВЕТАМ строк.
 *
 * <p><b>Зачем отдельный класс.</b> Это решение я за день менял четыре раза и
 * дважды сломал игру: сперва весь экран профиля стал фиолетовым, потом перестали
 * переводиться подсказки с заголовком. Причина не в сложности правила, а в том,
 * что <b>проверить его было нечем</b>: дамп снимает §-коды, цвета до
 * инструментов не доезжают, и каждая правка уходила к игроку непроверенной.
 *
 * <p>Поэтому логика вынесена сюда и НЕ ЗНАЕТ ПРО MINECRAFT: на входе список
 * названий цветов, на выходе решение с причиной. Такой класс компилируется
 * и запускается отдельно, значит его можно прогнать по записанным из игры
 * раскладкам и увидеть, что именно изменится, ДО сборки.
 *
 * <p>Раскладки пишет сам мод в {@code dump/color-cases.json}, проверяет
 * {@code tools/check_colors.py}.
 *
 * <p><b>Что защищаем.</b> Перенос абзаца красит все получившиеся строки цветом
 * первой. Для прозы это незаметно, а для размеченного блока — потеря смысла:
 * <ul>
 * <li>магазин: «Cost» серый / «10 Coins» золотой — пара «подпись и значение»;
 * <li>экран профиля: у каждой характеристики свой цвет, это таблица.
 * </ul>
 */
public final class ColorLayout {

	/** Что решили и почему. Причина нужна отчёту, а не движку. */
	public record Verdict(boolean merge, String reason) {
	}

	/** Меньше трёх строк — «подпись и значение», склеивать нельзя. */
	private static final int MIN_HEADER_RUN = 3;

	/**
	 * Сколько разных цветов ещё считается «заголовок и описание».
	 * Больше — это разметка: таблица характеристик или список полей.
	 */
	private static final int MAX_HEADER_COLORS = 3;

	private ColorLayout() {
	}

	/**
	 * Цвет, которым Hypixel набирает ОПИСАНИЕ. Заголовком такая строка не бывает:
	 * подпись он всегда красит (золотым, тёмно-красным, жёлтым).
	 */
	private static final Set<String> BODY_COLORS = Set.of("gray", "dark_gray");

	/** Кусок начинается строкой цвета описания? */
	private static boolean startsGray(List<String> colors) {
		return !colors.isEmpty() && BODY_COLORS.contains(colors.get(0));
	}

	/**
	 * Серая ли проза ПОД первой строкой — то есть заголовок это, а не таблица.
	 *
	 * <p>Считаем строки со второй: у «имя (время) / серое описание» серых
	 * половина и больше, у таблицы характеристик — ни одной.
	 */
	private static boolean bodyMostlyGray(List<String> colors) {
		if (colors.size() < 2) {
			return false;
		}
		int gray = 0;
		for (String color : colors.subList(1, colors.size())) {
			if (BODY_COLORS.contains(color)) {
				gray++;
			}
		}
		return gray * 2 >= colors.size() - 1;
	}

	/**
	 * Знак, с которого начинаются хотя бы две строки. null — списка нет.
	 *
	 * <p>⚠️ Публичный НАРОЧНО: по этому же знаку {@code Paragraphs.listed} режет
	 * найденный перевод обратно на пункты. Вывести знак заново там нельзя —
	 * маркером считается любой не-буквенный символ, и в маркеры попадают «{»
	 * от дырки «{n}» и «(» от скобки. Резка по ним разложила бы пункты по
	 * случайным местам. Один признак — одно место, иначе разойдётся.
	 */
	public static String repeatedMarker(List<String> markers) {
		Map<String, Integer> seen = new HashMap<>();
		for (String marker : markers) {
			if (!marker.isEmpty()) {
				seen.merge(marker, 1, Integer::sum);
			}
		}
		String twice = seen.entrySet().stream()
				.filter(entry -> entry.getValue() >= 2)
				.map(Map.Entry::getKey)
				.findFirst()
				.orElse(null);
		if (twice != null) {
			return twice;
		}
		// ⚠️ У списка-ВЫБОРА маркер стоит только на выбранном пункте:
		//     «▶ No filter / Common / Uncommon / Rare / Epic …»
		// Требование «знак повторяется дважды» такой список пропускало, и после
		// снятия защиты по цветам он склеился в сплошную строку — «▶ Без фильтра
		// Обычный Необычный Редкий Эпический…», читать невозможно. Значит хватает
		// ОДНОГО маркера, если строк много: проза с «▶» в начале бывает, а вот
		// проза из четырёх строк, где первая помечена значком, — нет.
		// ⚠️ …но ТОЛЬКО если знак действительно списочный.
		//
		// Одинокий знак бывает и у прозы: цитата открывается кавычкой, а имя
		// автора идёт после тире — «"What is the benefit… / – Plumber Joe».
		// Пять строк, знак у первой — и правило объявляло это списком, гася
		// готовый перевод. Для ПОВТОРЯЮЩЕГОСЯ знака такой проверки не нужно:
		// проза не начинает две строки одним и тем же значком.
		// ⚠️ Знак ищем В ЛЮБОЙ строке, а не только в первой. У списка-выбора
		// он стоит на ВЫБРАННОМ пункте, и стоит игроку выбрать не первый —
		// «Без фильтра / ▶ Обычный / Необычный / …» — как защита переставала
		// срабатывать, и список слипался в кашу: «Без фильтра ▶ Обычный
		// Необычный Редкий Эпический». Пока фильтр не тронут, маркер стоит
		// первым, и беда не видна — потому и не поймалась раньше.
		// ⚠️ Порог РАЗНЫЙ для двух видов знаков, и это не придирка.
		//
		// «▶» и «✔» — маркеры ВЫБОРА, прозу ими не начинают: трёх строк хватает,
		// и без этого фильтр аукциона «▶ Show All / BIN Only / Auctions Only»
		// склеивался в «▶ Показать все Только BIN».
		//
		// А значки приватной зоны (❈ ⚔ ☘) помечают ХАРАКТЕРИСТИКИ и стоят
		// в начале обычной прозы: «Gain +5 ❈ Defense, ⚔ Strength…». Для них
		// порог выше, иначе правило гасит переводы у трёхстрочных описаний.
		if (markers.size() >= MIN_CHOICE_LINES) {
			for (String marker : markers) {
				if (CHOICE_MARKS.contains(marker)) {
					return marker;
				}
			}
		}
		if (markers.size() >= MIN_ICON_LINES) {
			for (String marker : markers) {
				if (listMark(marker)) {
					return marker;
				}
			}
		}
		return null;
	}

	/**
	 * Знак, с которого начинается ПУНКТ списка или строка таблицы.
	 *
	 * <p>⚠️ Значки Hypixel (приватная зона юникода: ❤ ⚔ ❈ ✦) сюда входят
	 * обязательно — ими помечены строки таблицы характеристик на экране
	 * профиля. Склеить её нельзя: получится одна строка вместо десяти, и весь
	 * профиль перекрасится в один цвет. Это ровно тот случай, на котором проект
	 * уже обжигался, а перевод для таблицы в словаре ЕСТЬ — значит до цветов
	 * дело доходит, и защита обязана сработать.
	 *
	 * <p>⚠️ Публичный НАРОЧНО, и разница с {@link #repeatedMarker} тут
	 * существенная. Для ОТКАЗА в склейке годится любой повторяющийся знак:
	 * ошибиться в эту сторону дёшево — строки переведутся построчно. А вот
	 * РЕЗАТЬ найденный перевод можно только по настоящему списочному знаку.
	 * «{» от дырки «{n}» и «-» от дефиса тоже повторяются в начале строк,
	 * но встречаются и в середине текста — и разрез уехал бы в случайное
	 * место. {@code Paragraphs.listed} спрашивает именно этот метод.
	 */
	public static boolean listMark(String marker) {
		if (marker.isEmpty()) {
			return false;
		}
		if (CHOICE_MARKS.contains(marker)) {
			return true;
		}
		char first = marker.charAt(0);
		// Приватная зона юникода — там живут значки Hypixel. Пишем
		// escape-последовательностями: сами символы в исходнике невидимы,
		// и строку потом не прочитать глазами.
		return first >= '' && first <= '';
	}

	/**
	 * По этому знаку можно РЕЗАТЬ найденный перевод на пункты?
	 *
	 * <p>⚠️ Вопрос не тот же, что «делает ли знак абзац списком», и путать их
	 * дорого — на этом уже сломались 13 подсказок классов. Разница такая:
	 *
	 * <ul>
	 *   <li><b>Списком</b> абзац признаётся по {@link #repeatedMarker}, и там
	 *       одинокого знака при трёх строках достаточно. Ошибиться дёшево:
	 *       строки переведутся построчно.</li>
	 *   <li><b>Резать</b> можно только по знаку, который ТОЧНО помечает пункт.
	 *       «{» от дырки «{n}» и «-» от дефиса тоже повторяются в начале строк,
	 *       но встречаются и в середине текста — разрез уехал бы в случайное
	 *       место.</li>
	 * </ul>
	 *
	 * <p>«∙» (U+2219) разрешён здесь, но НЕ входит в {@link #CHOICE_MARKS}:
	 * им помечают и пункт списка, и заголовок с описанием («∙ Class Passive:
	 * Renew» и следом проза). Как список такой абзац опознаётся только при
	 * ПОВТОРЕ знака — а раз опознан, резать по нему уже безопасно.
	 */
	public static boolean cutMark(String marker) {
		return listMark(marker) || EXTRA_CUT.contains(marker);
	}

	/**
	 * Знаки, по которым РЕЗАТЬ можно, а объявлять список по ним — нельзя.
	 *
	 * <p>«∙» (U+2219) ставится и у пункта, и у заголовка с описанием под ним,
	 * поэтому в {@link #CHOICE_MARKS} ему нельзя (там порог всего три строки
	 * при одиноком знаке) — но раз абзац уже признан списком по ПОВТОРУ,
	 * резать по нему безопасно.
	 *
	 * <p>«✧» (U+2727) и «✦» (U+2726) — пункты бонуса сезонов: Hypixel помечает
	 * «✦» ТЕКУЩИЙ сезон, а «✧» остальные три. Без них перевод абзаца не
	 * применялся вовсе: склейку запрещал повтор «✧», а резать по нему было
	 * нельзя, и на экране половина сезонов оставалась английской.
	 *
	 * <p>«+» — пункты перечня привилегий («+ Start with a Grappling Hook»,
	 * меню Bingo). В {@link #CHOICE_MARKS} ему нельзя КАТЕГОРИЧЕСКИ: им
	 * начинаются 402 строки характеристик («+{n} Hunter Fortune»), и там порог
	 * в три строки погасил бы тысячи готовых абзацев прозы. А вот резать по
	 * нему безопасно ровно по тому же доводу, что у «∙»: абзац признаётся
	 * списком только при ПОВТОРЕ знака, то есть решение уже принято до нас.
	 * Без этого перевод меню привилегий лежал мёртвым грузом — склейку
	 * запрещал повтор «+», а применить перевод было нечем.
	 */
	private static final Set<String> EXTRA_CUT = Set.of("∙", "✧", "✦", "+");

	/**
	 * Знаки, которыми Hypixel помечает ВЫБРАННЫЙ пункт списка.
	 *
	 * <p>Кавычек, тире и скобок тут нет намеренно: они открывают обычную прозу.
	 */
	private static final Set<String> CHOICE_MARKS =
			Set.of("▶", "▸", "➤", "✔", "✖", "◼", "◆", "‣", "•", "▪", "»",
					// ⚠️ «∙» (U+2219) СЮДА НЕ ДОБАВЛЯТЬ, хотя глазом он
					// неотличим от «•» (U+2022). Пробовал — сломал 13 живых
					// подсказок, и вот чем они отличаются от списка:
					//
					//   ∙ Class Passive: Renew
					//   Grants 1.5x ❤ Mending, which increases…
					//
					// «∙» тут стоит у ОДНОЙ строки, а дальше идёт описание.
					// Это заголовок с прозой, а не перечисление: резать нечего,
					// склеить необходимо. А в CHOICE_MARKS порог всего три
					// строки при ОДИНОКОМ знаке — значит попадание сюда
					// запретило бы склейку и погасило готовый перевод.
					//
					// Настоящие списки с «∙» («Class Passives / ∙ Doubleshot /
					// ∙ Bone Plating») ловятся и без этого набора: там знак
					// ПОВТОРЯЕТСЯ, а повтор проверяется раньше и порога
					// не требует. Резать их разрешает cutMark.
					"○", "✓", "⋗", "⁍");

	/**
	 * Сколько строк нужно, чтобы одинокий МАРКЕР ВЫБОРА («▶», «✔») считался
	 * списком.
	 *
	 * <p>⚠️ Было 4, и список из ТРЁХ пунктов оставался без защиты: фильтр
	 * аукциона «▶ Show All / BIN Only / Auctions Only» склеивался
	 * в «▶ Показать все Только BIN».
	 */
	private static final int MIN_CHOICE_LINES = 3;

	/**
	 * То же для ЗНАЧКОВ приватной зоны (❈ ⚔ ☘) — порог выше.
	 *
	 * <p>Ими Hypixel помечает характеристики, и они спокойно стоят в начале
	 * обычной прозы: «Gain +5 ❈ Defense, ⚔ Strength…». На пороге 3 правило
	 * гасило готовые переводы у трёхстрочных описаний — проверено
	 * check_colors.py на живых раскладках.
	 */
	private static final int MIN_ICON_LINES = 4;

	/**
	 * @param leading     цвет начала каждой строки; «!» на конце означает, что
	 *                    ВНУТРИ строки цвет меняется
	 * @param allowHeader разрешено ли склеивать «заголовок + описание»
	 *                    (флаг {@code mergeHeaderRuns} в конфиге)
	 */
	public static Verdict decide(List<String> leading, boolean allowHeader) {
		return decide(leading, List.of(), allowHeader);
	}

	/**
	 * @param markers знак в начале каждой строки, если это НЕ буква и не цифра
	 *                («✔», «▶», «-»), иначе пустая строка
	 */
	public static Verdict decide(List<String> leading, List<String> markers, boolean allowHeader) {
		if (leading.size() < 2) {
			return new Verdict(false, "строк меньше двух");
		}
		// ⚠️ СПИСОК склеивать нельзя, какого бы он ни был цвета.
		//
		// «Includes: / ✔ Double Tap to Drop / ✔ Profile Viewer / ✔ Player
		// Trading …» — строки одноцветные, поэтому проверка по цвету их
		// пропускала, абзац склеивался и перенос размазывал список в сплошной
		// текст: «✔ Двойное нажатие для выброса ✔ Просмотр профиля ✔ Обмен
		// с игроками…». Читать это невозможно.
		//
		// Признак не гадательный: одинаковый ЗНАК в начале у нескольких строк —
		// это разметка списка, а не совпадение. Буквы и цифры не в счёт, иначе
		// под правило попала бы обычная проза.
		String listMarker = repeatedMarker(markers);
		if (listMarker != null) {
			return new Verdict(false, "строки начинаются с «" + listMarker + "» — это список");
		}
		// ⚠️ ВСЁ ОСТАЛЬНОЕ — склеиваем, и это главное решение этого класса.
		//
		// Сюда мы попадаем ТОЛЬКО когда перевод абзаца УЖЕ НАЙДЕН: Paragraphs.apply
		// спрашивает словарь раньше (match == null -> выход). А найтись перевод мог
		// лишь у куска, который признали абзацем ещё при сборке корпуса — он шёл
		// сплошным блоком без пустых строк, и переводчик видел его целиком.
		// Значит склейка тут не догадка, а факт, подтверждённый деньгами.
		//
		// Раньше здесь стояли пять условий, подобранных по случаям: «первая строка
		// разноцветная — заголовок с полями», «две строки разного цвета — подпись
		// и значение», «цветов больше трёх — таблица», «нет преобладающего цвета».
		// Каждое хоть раз ошиблось, и цена ошибки была невидимой: готовый перевод
		// гас молча, без ошибки и без лога, а игрок видел английский экран.
		// Замер на живых раскладках: из 13 отказов перевод куплен у ВСЕХ 13.
		//
		// ⚠️ Довод «а как же профиль, который стал фиолетовым» проверен и снят:
		// у «§cHealth 250 §aStrength 1,584.24 …» перевода в словаре НЕТ вовсе
		// (куски с характеристиками в корпус не берутся), поэтому до этого места
		// он не доходит. Стерегло правило беду, которой на этом пути уже нет.
		//
		// Цвета остаются нужны — но для того, ЧЕМ красить (ParagraphColors),
		// а не для того, показывать ли купленный текст.
		if (!allowHeader) {
			// выключатель строгого режима: mergeHeaderRuns=false возвращает прежнюю
			// осторожность — склеиваем только куски одного цвета
			boolean sameColor = true;
			for (String entry : leading) {
				sameColor &= entry.replace("!", "").equals(leading.get(0).replace("!", ""));
			}
			if (!sameColor) {
				return new Verdict(false, "цвета разные, склейка заголовков выключена");
			}
		}
		return new Verdict(true, "перевод абзаца найден — применяем");
	}
}
